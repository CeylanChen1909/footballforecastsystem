const DICTS = { zh: ZH, en: EN }
const FALLBACK_LOCALE = 'zh'
const [locale, setLocaleSignal] = createSignal(FALLBACK_LOCALE)

function lookup(key, loc) {
  const value = DICTS[loc]?.[key]
  if (value !== undefined) return value
  if (loc !== FALLBACK_LOCALE) return DICTS[FALLBACK_LOCALE][key]
  return undefined
}

/** t('matches.today') / t('matches.matchCount', { count: 3 })；缺 key 时返回 key 本身，开发模式 console.warn。 */
export function t(key, params) {
  const value = lookup(key, locale())
  if (value === undefined) {
    if (import.meta.env.DEV) console.warn(`[i18n] missing key: ${key}`)
    return key
  }
  if (Array.isArray(value)) return value
  if (!params) return value
  return String(value).replace(/\{(\w+)\}/g, (_, name) =>
    params[name] === undefined || params[name] === null ? '' : String(params[name]),
  )
}

/** r11 没有切换 UI；仅备后用。调用方不得凭空加语言切换按钮。 */
export function setLocale(next) {
  if (DICTS[next]) setLocaleSignal(next)
}

/** match.js 的用法：locale.value === 'zh' ? 'zh-CN' : 'en-US'。 */
export function dateLocale() {
  return locale() === 'zh' ? 'zh-CN' : 'en-US'
}

export function useI18n() {
  return { t, locale, setLocale }
}

export { locale }
export default { t, locale, setLocale, useI18n, dateLocale }
